const catalogs = { it, en } as const;
let current: Record<MessageKey, string> = it;

export function setLocale(locale: 'auto' | 'it' | 'en', navigatorLang = typeof navigator !== 'undefined' ? navigator.language : 'it'): 'it' | 'en' {
  const resolved = locale === 'auto' ? (navigatorLang.toLowerCase().startsWith('it') ? 'it' : 'en') : locale;
  current = catalogs[resolved];
  return resolved;
}

export function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
  return current[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export function countLabel(n: number): string {
  return n === 1 ? t('itemsOne') : t('items', { n });
}
